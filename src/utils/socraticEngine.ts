  const { message = '', history = [], tone = 'socrates', direction = 'web' } = ctx;
  const msg = message.trim();
  const lower = msg.toLowerCase();

  // Detect code patterns in user message
  const hasCode = /(=>|function|const |let |var |def |import |class |<[a-z]+>|console\.|print\(|for |while |if |return |pinMode|digitalWrite|void setup)/i.test(msg);

