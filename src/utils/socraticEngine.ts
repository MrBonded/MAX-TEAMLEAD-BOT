export interface LocalCodeReviewResult {
  score: number;
  summary: string;
  criticalIssues: Array<{
    line: number | null;
    type: string;
    description: string;
    socraticHint: string;
  }>;
  bestPractices: string[];
  praise: string;
}

export function analyzeCodeLocally(
  code: string,
  language = 'javascript',
  fileName = 'code.js'
): LocalCodeReviewResult {
  const lines = code.split('\n');
  const issues: LocalCodeReviewResult['criticalIssues'] = [];
  const langLower = (language || '').toLowerCase();

  // 1. Check Typos and Syntax per language
  lines.forEach((lineText, idx) => {
    const lineNum = idx + 1;
    const trimmed = lineText.trim();

    // JavaScript / TypeScript checks
    if (langLower.includes('js') || langLower.includes('javascript') || langLower.includes('ts')) {
      if (trimmed.includes('addEventListner')) {
        issues.push({
          line: lineNum,
          type: 'Опечатка',
          description: 'Опечатка в названии метода addEventListner (пропущена буква "e").',
          socraticHint: 'Сверься со словарем или MDN: слово Listener пишется с буквой "e" (addEventListener).'
        });
      }
      if (trimmed.includes('console.lag')) {
        issues.push({
          line: lineNum,
          type: 'Опечатка',
          description: 'Опечатка console.lag вместо console.log.',
          socraticHint: 'В объекте console метод вывода называется log.'
        });
      }
      if (trimmed.includes('getElementByID')) {
        issues.push({
          line: lineNum,
          type: 'Регистр букв',
          description: 'Метод пишется как getElementById (маленькая "d" на конце).',
          socraticHint: 'В JavaScript имена методов чувствительны к регистру (camelCase).'
        });
      }
      if (/\bif\s*\([^=!<>]=[^=]/.test(trimmed)) {
        issues.push({
          line: lineNum,
          type: 'Логика',
          description: 'Одиночный оператор присваивания "=" внутри условия "if" вместо сравнения "===".',
          socraticHint: 'Вспомни разницу между присваиванием значения переменной (=) и проверкой на равенство (===).'
        });
      }
    }

    // Python checks
    if (langLower.includes('py') || langLower.includes('python')) {
      if (trimmed.startsWith('def ') && !trimmed.endsWith(':') && !trimmed.includes('#')) {
        issues.push({
          line: lineNum,
          type: 'Синтаксис Python',
          description: 'Пропущено обязательное двоеточие ":" в конце определения функции def.',
          socraticHint: 'Каким знаком в Python всегда завершается заголовок функции или условия?'
        });
      }
      if (/\b(if|for|while|elif)\b.*[^:]$/.test(trimmed) && !trimmed.includes('#')) {
        issues.push({
          line: lineNum,
          type: 'Синтаксис Python',
          description: 'Пропущено двоеточие ":" в конце инструкции ' + trimmed.split(' ')[0] + '.',
          socraticHint: 'В Python блоки кода начинаются после двоеточия.'
        });
      }
      if (/range\(\s*len\([^)]+\)\s*\+\s*1\s*\)/.test(trimmed)) {
        issues.push({
          line: lineNum,
          type: 'Выход за границы (IndexError)',
          description: 'range(len(x) + 1) вызовет IndexError на последнем элементе списка.',
          socraticHint: 'Индексы в Python идут от 0 до len - 1. Нужна ли единица внутри range?'
        });
      }
      // Check def without indent on next line
      if (trimmed.startsWith('def ') && lines[idx + 1] && lines[idx + 1].trim().length > 0) {
        const nextLine = lines[idx + 1];
        if (nextLine.length > 0 && !nextLine.startsWith(' ') && !nextLine.startsWith('\t')) {
          issues.push({
            line: lineNum + 1,
            type: 'Ошибка отступов (IndentationError)',
            description: 'Тело функции должно иметь отступ (4 пробела).',
            socraticHint: 'В Python блоки кода отделяются отступами, а не фигурными скобками.'
          });
        }
      }
    }

    // HTML checks
    if (langLower.includes('html')) {
      if (trimmed.includes('<script') && !trimmed.includes('defer') && !trimmed.includes('async')) {
        // Minor notice if script in head
      }
    }
  });

  // 2. Global check for unbalanced brackets
  if (langLower.includes('js') || langLower.includes('javascript') || langLower.includes('ts')) {
    const openBraces = (code.match(/\{/g) || []).length;
    const closeBraces = (code.match(/\}/g) || []).length;
    if (openBraces !== closeBraces) {
      issues.push({
        line: lines.length,
        type: 'Синтаксис',
        description: `Несовпадение фигурных скобок: открыто ${openBraces}, закрыто ${closeBraces}.`,
        socraticHint: 'Проверь парность всех открывающих { и закрывающих } скобок в коде.'
      });
    }
  }

  // 3. HTML tag balance
  if (langLower.includes('html')) {
    const openDivs = (code.match(/<div[\s>]/g) || []).length;
    const closeDivs = (code.match(/<\/div>/g) || []).length;
    if (openDivs !== closeDivs) {
      issues.push({
        line: lines.length,
        type: 'Разметка HTML',
        description: `Не совпадает количество тегов <div>: открыто ${openDivs}, закрыто ${closeDivs}.`,
        socraticHint: 'Сосчитай открывающие <div...> и закрывающие </div> теги.'
      });
    }
  }

  // If no issues found: celebrate 100/100 clean code!
  if (issues.length === 0) {
    return {
      score: 100,
      summary: `Отличная работа! В файле ${fileName} не обнаружено критических ошибок и синтаксических сбоев. Код написан аккуратно и логично.`,
      criticalIssues: [],
      bestPractices: [
        'Используй осмысленные имена переменных и функций',
        'Разделяй крупную логику на небольшие функции',
        'Продолжай следовать правилам чистого кода (Clean Code)'
      ],
      praise: 'Код полностью готов к работе и запуску! Замечаний нет.'
    };
  }

  const score = Math.max(45, 100 - issues.length * 18);
  return {
    score,
    summary: `Код проанализирован. Обнаружено замечаний: ${issues.length}. Обрати внимание на указанные строки перед запуском программы.`,
    criticalIssues: issues,
    bestPractices: [
      'Всегда проверяй имена встроенных методов на опечатки',
      'Внимательно следи за синтаксисом и отступами',
      'Проверяй краевые случаи работы функций'
    ],
    praise: 'Хорошая идея решения! Исправь найденные моменты, и всё заработает идеально.'
  };
}
