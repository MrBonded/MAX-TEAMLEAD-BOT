/**
 * Умный Сократовский диалоговый движок для бота AI-Тимлида «Макс»
 * Команда: «Галактические боты» (МБОУДО ДЮЦКО «Галактика» г. Калуги)
 */

export function generateSocraticResponse({ message = '', history = [], tone = 'socrates', direction = 'web' }) {
  const msg = message.trim();
  const lower = msg.toLowerCase();

  const hasCode = /(=>|function|const |let |var |def |import |class |<[a-z]+>|console\.|print\(|for |while |if |return |pinMode|digitalWrite|void setup)/i.test(msg);

  const tonePrefix = {
    socrates: '🏛️ **AI-Тимлид Макс (Метод Сократа)**:\n\n',
    buddy: '🤝 **Твой бадди Макс на связи!**\n\n',
    lead: '👔 **Code Review & Архитектура (Senior Тимлид)**:\n\n',
  }[tone] || '🏛️ **AI-Тимлид Макс**:\n\n';

  const pick = (arr) => {
    const seed = msg.length + (history.length * 7) + (msg.charCodeAt(0) || 0) + (msg.charCodeAt(msg.length - 1) || 0);
    return arr[Math.abs(seed) % arr.length];
  };

  // 1. Приветствие
  if (/(привет|здравствуй|хай|салют|добрый день|добрый вечер|ку|хей|доброе утро)/i.test(lower)) {
    const greetings = [
      `${tonePrefix}Рад приветствовать в нашей IT-лаборатории! Я твой персональный наставник.

Чем сегодня занимаемся?
• 💻 **Пишем код** (JavaScript, Python, HTML/CSS)?
• ⚡ **Собираем схему** на макетной плате (Arduino, ESP32, датчики)?
• 🚀 **Настраиваем Docker** и бота в мессенджере МАКС?

Присылай строчку кода или вопрос!`,
      `${tonePrefix}Привет, коллега! Готов к продуктивной разработке.

Я работаю по Сократовскому методу: не выдаю готовые решения на блюдечке, а помогаю понять первопричину бага!

Над чем ты сейчас работаешь? Задавай вопрос!`,
      `${tonePrefix}Здорово! Наставник на посту.

Помни золотое правило лаборатории: **«Любой баг — это просто программа, выполняющая то, что ты написал, а не то, что ты имел в виду!»** 😄

Что разберем прямо сейчас?`
    ];
    return { reply: pick(greetings), isCode: false };
  }

  // 2. Кто ты / О боте
  if (/(кто ты|о тебе|что ты умеешь|твоя команда|галактик|калуг|расскажи о себе)/i.test(lower)) {
    return {
      reply: `${tonePrefix}Я — **AI-Тимлид «Макс»**, цифровой наставник для будущих инженеров и программистов.
Создан командой **«Галактические боты»** из **МБОУДО ДЮЦКО «Галактика» г. Калуги**.

🎯 **Моя миссия**:
1. **Сократовский диалог**: учу находить баги самостоятельно через наводящие вопросы.
2. **Code Review**: проверка JS, Python, HTML/CSS на опечатки и безопасность.
3. **IoT-лаборатория**: предотвращение подачи 5V вместо 3.3V, контроль резисторов и общей земли (GND).
4. **Интеграция с МАКС**: запуск прямо в мессенджере через платформу dev.max.ru.`,
      isCode: false
    };
  }

  // 3. Благодарность / Успех
  if (/(спасибо|спс|благодарю|ура|заработало|получилось|помогло|красавчик|топ)/i.test(lower)) {
    const thanks = [
      `${tonePrefix}Отличная работа! 🎉 Ты докопался до сути сам — именно так растет настоящий Senior! Двигаемся к следующей фиче?`,
      `${tonePrefix}Супер! Поздравляю с побежденным багом! 🚀 Теперь ты точно знаешь механику этой ошибки. Что пишем дальше?`,
      `${tonePrefix}Так держать! 🏆 Победа над хитрым багом — лучший момент в кодинге. Присылай следующий фрагмент!`
    ];
    return { reply: pick(thanks), isCode: false };
  }

  // 4. Юмор
  if (/(шутк|анекдот|мем|рассмеши|веселей|пошути)/i.test(lower)) {
    const jokes = [
      `${tonePrefix}Лови классику от IT-Тимлида:
— Папа, а почему солнце каждое утро встает на востоке и садится на западе?
— Сынок, ты это проверял?
— Да, работает каждый день.
— Работает — **не трогай!** 😅

А как поживает твой код? Работает или трогаем?`,
      `${tonePrefix}Знаешь разницу между джуном и сеньором?
Джун думает, что баг в компиляторе.
Сеньор знает, что баг в 12-й строчке, но еще 3 часа ищет потерянную скобку! 😉`
    ];
    return { reply: pick(jokes), isCode: false };
  }

  // 5. Опечатка в addEventListener / DOM события
  if (/addeventlist(ner|ener)|listener|кнопк|click|клик/i.test(lower)) {
    return {
      reply: `${tonePrefix}Разбираем обработку событий в браузере:

🔍 **Частая ловушка — Опечатка**:
Метод пишется строго \`addEventListener\` (проверь букву **e** перед **ner**). Опечатка \`addEventListner\` вызовет:
\`TypeError: submitBtn.addEventListner is not a function\`.

🔍 **Скрипт выполнился раньше разметки**:
Если \`document.querySelector()\` отработал до отрисовки кнопки, переменная будет \`null\`.

💡 **Проверь**: что выведет \`console.log(кнопка)\` строго перед вызовом события?`,
      isCode: true
    };
  }

  // 6. null / undefined / TypeError
  if (/(cannot read propert|undefined|null|is not a function|typeerror|nan)/i.test(lower)) {
    return {
      reply: `${tonePrefix}Знакомая ситуация! \`Cannot read properties of undefined\` или \`null\` означает:
Переменная слева от точки пуста или еще не загрузилась.

💡 **Как локализовать**:
1. Посмотри в ошибке на слово ПОСЛЕ слова *reading* — это свойство, к которому шло обращение.
2. Поставь отладку перед этой строкой:
\`\`\`javascript
console.log('Значение объекта:', myVariable);
\`\`\`
3. Используй безопасный оператор: \`myVariable?.property\`.

Какая именно переменная у тебя сейчас не определена?`,
      isCode: true
    };
  }

  // 7. Python: IndexError, отступы, списки
  if (/(indexerror|list index out of range|indentationerror|отступ|taberror|python|питон|range)/i.test(lower)) {
    return {
      reply: `${tonePrefix}Разбираем ошибки в Python:

🐍 **IndexError: list index out of range**:
В Python индексы начинаются с **0**! Если в списке 3 элемента, то индексы: \`0, 1, 2\`.
Попытка взять \`items[3]\` уронит скрипт!

\`\`\`python
# ✅ Безопасный перебор элементов списка:
for item in my_list:
    print(item)
\`\`\`

🐍 **IndentationError**:
Python требует строго 4 пробела для каждого уровня вложенности. Не смешивай пробелы и Tab!`,
      isCode: true
    };
  }

  // 8. Центрирование в CSS / Flexbox / Grid
  if (/(отцентрировать|по центру|flexbox|grid|css|верстк|div|стил|margin auto)/i.test(lower)) {
    return {
      reply: `${tonePrefix}📐 **Центрирование блока по современным стандартам**:

Используй **Flexbox** у родительского контейнера:
\`\`\`css
.parent {
  display: flex;
  justify-content: center; /* по горизонтали */
  align-items: center;     /* по вертикали */
  min-height: 100vh;
}
\`\`\`

Или CSS Grid в 2 строки:
\`\`\`css
.parent {
  display: grid;
  place-items: center;
}
\`\`\``,
      isCode: true
    };
  }

  // 9. IoT: Датчик DHT11, 5V vs 3.3V
  if (/(dht11|dht22|датчик|5v|3\.3v|3v|греется|вольт|напряжен|питани)/i.test(lower)) {
    return {
      reply: `${tonePrefix}⚡ **ВНИМАНИЕ, ЭЛЕКТРОБЕЗОПАСНОСТЬ!**

Если датчик или чип греется — **немедленно вытащи USB-кабель из компьютера!**

1. Контроллеры ESP32 и STM32 работают СТРОГО от **3.3 Вольт**.
2. Сенсор DHT11 очень чувствителен к перенапряжению.
3. Проверь: красный провод подключен к пину 3.3V или случайно попал в 5V? Совпадает ли земля (GND)?`,
      isCode: false
    };
  }

  // 10. IoT: Светодиод и резистор 220 Ом
  if (/(светодиод|диод|резистор|220|330|ом|сопротивлен|led)/i.test(lower)) {
    return {
      reply: `${tonePrefix}💡 **Закон Ома**:
Никогда не подключай светодиод к пину Arduino/ESP32 напрямую без резистора!

Ток превысит 70-100 мА, и порт контроллера выгорит за несколько секунд.
Всегда ставь резистор на **220–330 Ом** последовательно с ножкой светодиода.`,
      isCode: false
    };
  }

  // 11. Docker
  if (/(docker|докер|docker-compose|контейнер|порт 3000|compose)/i.test(lower)) {
    return {
      reply: `${tonePrefix}🐳 **Команды для управления контейнерами Docker**:

\`\`\`bash
# Запуск в фоновом режиме со сборкой:
docker compose up --build -d

# Просмотр логов бота МАКС:
docker compose logs -f max-bot

# Проверить статус:
docker compose ps
\`\`\`

Бот подключается к серверам МАКС через исходящий Long Polling, поэтому открывать порты для бота не требуется.`,
      isCode: true
    };
  }

  // 12. Мессенджер МАКС
  if (/(мессенджер макс|dev\.max\.ru|токен|бот|мини апп|mini app|openapp)/i.test(lower)) {
    return {
      reply: `${tonePrefix}🇷🇺 **Подключение к отечественному мессенджеру МАКС**:

1. Создай бота в кабинете разработчика на [dev.max.ru](https://dev.max.ru).
2. Скопируй полученный токен в файл \`.env\` в строчку:
   \`BOT_TOKEN="max_bot_твой_токен"\`
3. Укажи адрес веб-приложения:
   \`WEBAPP_URL="http://localhost:3000"\`
4. В мессенджере нажми кнопку **«🚀 Открыть IT-Лабораторию»** для запуска Mini App!`,
      isCode: true
    };
  }

  // 13. Разговоры не по теме, усталость, эмоции (Режим Чат-Наставник)
  if (/(как дела|как жизнь|как поживаешь|что делаешь|чем занят|что нового)/i.test(lower)) {
    const lifeAnswers = [
      `${tonePrefix}У меня всё отлично! В нашей лаборатории кипит работа: тестируем код и проверяем датчики. 

А у тебя как настрой? Отдыхаешь или настраиваешься на кодинг?`,
      `${tonePrefix}Тимлид на посту! Слежу за архитектурой проектов. Как твои успехи сегодня?`
    ];
    return { reply: pick(lifeAnswers), isCode: false };
  }

  if (/(я устал|устала|хочу спать|мне лень|мне скучно|скукота|нет настроения|тяжело|надоело|выгорел)/i.test(lower)) {
    const supportAnswers = [
      `${tonePrefix}Слушай, отдых — это обязательная часть инженерного процесса!

Мозг часто находит решение проблемы, когда ты отходишь от экрана и пьешь чай. Сделай паузу на 15 минут, перезагрузись, а код никуда не убежит!`,
      `${tonePrefix}Понимаю! Если голова перегружена, не дави на себя. Закрой ноутбук или отойди от макетки, прогуляйся — наставник одобряет законный тайм-аут! 😉`
    ];
    return { reply: pick(supportAnswers), isCode: false };
  }

  if (/(не получается|я глупый|я тупой|не понимаю|брошу|бросить|бесит|не мое)/i.test(lower)) {
    return {
      reply: `${tonePrefix}Так, отставить самокритику!

Каждый Senior когда-то часами не понимал простейший цикл. Ошибки — единственный способ научиться. Давай выдохнем и разберем задачу на самые простые шаги. Я рядом и помогу!`,
      isCode: false
    };
  }

  if (/(поговори со мной|поболтаем|расскажи что|о чем думаешь|поговорим)/i.test(lower)) {
    return {
      reply: `${tonePrefix}С удовольствием! Хороший наставник всегда готов не только код проверять, но и пообщаться по душам. О чем поболтаем?`,
      isCode: false
    };
  }

  // 14. Анализ вставленного кода
  if (hasCode) {
    return {
      reply: `${tonePrefix}Вижу твой фрагмент кода!

🔍 **Давай взглянем на него вместе**:
1. Что именно должна вернуть эта функция при правильной работе?
2. Что сейчас выводится в терминале или консоли браузера?
3. Пробовал ли ты добавить отладочный вывод (\`console.log\` или \`print\`) прямо перед проблемной строчкой?

Опиши суть задачи, и мы разберем её!`,
      isCode: true
    };
  }

  // 15. Естественный ответ наставника на общие вопросы
  const defaultVariants = [
    `${tonePrefix}Слушаю тебя внимательно! Как твой наставник, я здесь, чтобы помочь во всем разобраться — будь то программирование, электроника или совет по проектам.

Расскажи подробнее, что у тебя на уме?`,

    `${tonePrefix}Понял тебя! Давай обсудим. Если это вопрос по коду — распутаем любой баг, а если просто хочется пообщаться — с радостью поддержу разговор. С чего начнем?`
  ];

  return { reply: pick(defaultVariants), isCode: false };
}
